// configuration is a run credentials document of the fixture starter with the keys
// given, its public_key_file names relative to the directory of the known answers.
func configuration(algorithms []string, keys []map[string]string) []map[string]any {
	return []map[string]any{{
		"issuer":       Issuer,
		"audience":     Audience,
		"algorithms":   algorithms,
		"keys":         keys,
		"leeway":       "60s",
		"max_lifetime": "1h",
		"allow":        map[string]any{"claim": "namespace", "values": []string{"example-namespace"}},
		"labels": map[string]any{
			"forge":      map[string]string{"value": "example-forge"},
			"repository": map[string]any{"claims": []string{"namespace", "project"}, "join": "/"},
			"run_key":    map[string]string{"claim": "sub"},
		},
		"details": map[string]any{"requester": map[string]string{"claim": "requester"}},
	}}
}

// Case is one run credential and its outcome.
type Case struct {
	Name          string `json:"name"`
	Configuration string `json:"configuration"`
	Credential    string `json:"credential"`
	// Outcome is accepted or refused.
	Outcome string `json:"outcome"`
	// RefusedAt is the step that refuses a refused run credential: header, signature,
	// claims, scope or mapping.
	RefusedAt string            `json:"refused_at,omitempty"`
	Labels    map[string]string `json:"labels,omitempty"`
	Details   map[string]string `json:"details,omitempty"`
	Note      string            `json:"note"`
}

// claims are the claims of a valid run credential at [Now], with changes: a nil value
// removes the claim.
func claims(changes map[string]any) map[string]any {
	c := map[string]any{
		"iss":       Issuer,
		"aud":       Audience,
		"sub":       "rk-0001",
		"iat":       Now - 60,
		"exp":       Now + 600,
		"namespace": "example-namespace",
		"project":   "project",
		"requester": "example-requester",
	}
	for k, v := range changes {
		if v == nil {
			delete(c, k)
		} else {
			c[k] = v
		}
	}
	return c
}

var b64 = base64.RawURLEncoding

// segment is the base64url of a JSON object, its members sorted by name.
func segment(v any) string { return b64.EncodeToString(mustJSON(v)) }

// mustJSON is the JSON text of v, an object's members sorted by name.
func mustJSON(v any) []byte {
	b, err := json.Marshal(v)
	if err != nil {
		panic(err)
	}
	return b
}

// signer signs the signing input of a JWS.
type signer func(input []byte) ([]byte, error)

// sign is the JWS compact serialisation of the header and claims under s; a nil s
// leaves the signature empty.
func sign(header, payload map[string]any, s signer) (string, error) {
	return signRaw(segment(header), segment(payload), s)
}

// signRaw is the JWS compact serialisation of the encoded header and payload under s.
func signRaw(header, payload string, s signer) (string, error) {
	input := header + "." + payload
	if s == nil {
		return input + ".", nil
	}
	sig, err := s([]byte(input))
	if err != nil {
		return "", err
	}
	return input + "." + b64.EncodeToString(sig), nil
}

// signatureChanged is s with its signature changed by change.
func signatureChanged(s signer, change func([]byte) []byte) signer {
	return func(input []byte) ([]byte, error) {
		sig, err := s(input)
		if err != nil {
			return nil, err
		}
		return change(sig), nil
	}
}

// p256Order is the order n of P-256's base point, 32 bytes, big endian.
func p256Order() []byte {
	return elliptic.P256().Params().N.FillBytes(make([]byte, 32))
}

// partChanged is a change to one part of a JWS compact serialisation.
func partChanged(n int, change func(string) string) func(string) string {
	return func(cred string) string {
		parts := strings.Split(cred, ".")
		parts[n] = change(parts[n])
		return strings.Join(parts, ".")
	}
}

