// Now is the clock every outcome holds at, in seconds since the epoch: the clock the
// signed fixtures of the contract are replayed at.
const Now = 1700000000

// Seed is the fixture starter's seed, bytes 193 to 224.
func Seed() []byte {
	s := make([]byte, 32)
	for n := range s {
		s[n] = byte(193 + n)
	}
	return s
}

// derive is SHA-256 of the seed followed by the label's bytes and the counter, one
// byte.
func derive(seed []byte, label string, counter byte) []byte {
	h := sha256.New()
	h.Write(seed)
	h.Write([]byte(label))
	h.Write([]byte{counter})
	return h.Sum(nil)
}

// prime is the first prime p at or above a candidate of 1024 bits, the candidate being
// SHA-256 of the seed, the label and the counters 0 to 3 concatenated, with its two
// highest bits and its lowest bit set, searched upward in steps of two, such that
// p - 1 is not a multiple of 65537.
func prime(seed []byte, label string) *big.Int {
	var b []byte
	for c := range byte(4) {
		b = append(b, derive(seed, label, c)...)
	}
	b[0] |= 0xc0
	b[len(b)-1] |= 1
	p := new(big.Int).SetBytes(b)
	e := big.NewInt(65537)
	two := big.NewInt(2)
	one := big.NewInt(1)
	for {
		if p.ProbablyPrime(32) {
			pm1 := new(big.Int).Sub(p, one)
			if new(big.Int).Mod(pm1, e).Sign() != 0 {
				return p
			}
		}
		p.Add(p, two)
	}
}

// Keys are the fixture starter's private keys.
type Keys struct {
	RSA     *rsa.PrivateKey
	ECDSA   *ecdsa.PrivateKey
	Ed25519 ed25519.PrivateKey
}

// DeriveKeys derives the fixture starter's keys from the seed:
//
//   - RSA: p is prime(seed, "rs256-p"), q is prime(seed, "rs256-q"), e is 65537, d is
//     the inverse of e modulo lcm(p-1, q-1), so the modulus has 2048 bits;
//   - ECDSA on P-256: the private scalar is SHA-256(seed || "es256" || 0x00), big
//     endian;
//   - Ed25519: the seed of the key is SHA-256(seed || "eddsa" || 0x00).
func DeriveKeys(seed []byte) (*Keys, error) {
	p, q := prime(seed, "rs256-p"), prime(seed, "rs256-q")
	if p.Cmp(q) == 0 {
		return nil, fmt.Errorf("p equals q")
	}
	one := big.NewInt(1)
	pm1, qm1 := new(big.Int).Sub(p, one), new(big.Int).Sub(q, one)
	g := new(big.Int).GCD(nil, nil, pm1, qm1)
	lambda := new(big.Int).Div(new(big.Int).Mul(pm1, qm1), g)
	e := big.NewInt(65537)
	d := new(big.Int).ModInverse(e, lambda)
	if d == nil {
		return nil, fmt.Errorf("e has no inverse")
	}
	rk := &rsa.PrivateKey{
		PublicKey: rsa.PublicKey{N: new(big.Int).Mul(p, q), E: 65537},
		D:         d,
		Primes:    []*big.Int{p, q},
	}
	if rk.N.BitLen() != 2048 {
		return nil, fmt.Errorf("the modulus has %d bits", rk.N.BitLen())
	}
	rk.Precompute()
	if err := rk.Validate(); err != nil {
		return nil, err
	}
	ek, err := ecdsa.ParseRawPrivateKey(elliptic.P256(), derive(seed, "es256", 0))
	if err != nil {
		return nil, err
	}
	return &Keys{RSA: rk, ECDSA: ek, Ed25519: ed25519.NewKeyFromSeed(derive(seed, "eddsa", 0))}, nil
}

// FixtureKeys are the DER SubjectPublicKeyInfo of the fixture starter's public keys, in
// the order rs256.pem, es256.pem, eddsa.pem.
func FixtureKeys() ([][]byte, error) {
	k, err := DeriveKeys(Seed())
	if err != nil {
		return nil, err
	}
	var out [][]byte
	for _, pub := range []crypto.PublicKey{&k.RSA.PublicKey, &k.ECDSA.PublicKey, k.Ed25519.Public()} {
		der, err := x509.MarshalPKIXPublicKey(pub)
		if err != nil {
			return nil, err
		}
		out = append(out, der)
	}
	return out, nil
}

// FixtureKeysSource is the Go source of runcredential/fixturekeys.go: the variable
// fixtureKeys, the [FixtureKeys] in standard base64.
func FixtureKeysSource() ([]byte, error) {
	keys, err := FixtureKeys()
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate ./runcredential; DO NOT EDIT.\n\n")
	b.WriteString("package runcredential\n\n")
	b.WriteString("// fixtureKeys are the DER SubjectPublicKeyInfo, in standard base64, of the contract's\n")
	b.WriteString("// published fixture keys: rs256.pem, es256.pem and eddsa.pem of the known answers of\n")
	b.WriteString("// the run credential. Their seed is public, so [Key.PublicKey] refuses each.\n")
	b.WriteString("var fixtureKeys = []string{\n")
	for _, der := range keys {
		fmt.Fprintf(&b, "\t%q,\n", base64.StdEncoding.EncodeToString(der))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// PEM is a public key as one PEM block of type PUBLIC KEY.
func PEM(pub crypto.PublicKey) ([]byte, error) {
	der, err := x509.MarshalPKIXPublicKey(pub)
	if err != nil {
		return nil, err
	}
	return pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: der}), nil
}

